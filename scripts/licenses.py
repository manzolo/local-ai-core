"""licenses.py — writes docs/licenses-python.md: every pinned Python package and its license, from PyPI.

  python3 scripts/licenses.py          (needs network; run it after changing requirements/*.txt)

The license comes from the package metadata (license expression, else classifiers, else the license
field). NVIDIA's CUDA wheels often declare nothing: they are listed as NVIDIA software under NVIDIA's terms.
"""
import concurrent.futures as cf
import json
import os
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = {"runtime.txt": "gateway, search", "documents.txt": "documents", "dev.txt": "tests only"}


def pins():
    used = {}
    for f, who in FILES.items():
        for line in open(os.path.join(ROOT, "requirements", f)):
            line = line.strip()
            if "==" in line and not line.startswith("#"):
                name, ver = line.split("==")
                used.setdefault((name, ver), []).append(who)
    return used


def license_of(name, ver):
    d = json.load(urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{ver}/json", timeout=30))["info"]
    lic = d.get("license_expression") or ""
    if not lic:
        lic = "; ".join(c.split(" :: ")[-1] for c in d.get("classifiers", []) if c.startswith("License ::"))
    if not lic:
        lic = (d.get("license") or "").split("\n")[0][:80]
    if not lic and (name.startswith("nvidia-") or name.startswith("cuda-")):
        lic = "NVIDIA software, NVIDIA terms (no license metadata on PyPI)"
    return lic or "not declared"


def main():
    used = pins()
    with cf.ThreadPoolExecutor(16) as ex:
        lic = dict(zip(used, ex.map(lambda p: license_of(*p), used), strict=True))
    rows = sorted(used, key=lambda p: p[0].lower())
    out = ["# Python packages and their licenses", "", "[← back to the licenses](licenses.md)", "",
           "Every package installed in the images, pinned in `requirements/`, with the license its PyPI "
           "metadata declares. None is GPL or AGPL. Generated by `scripts/licenses.py`: do not edit by hand.", "",
           "| Package | Version | License | Used by |", "|---|---|---|---|"]
    for name, ver in rows:
        out.append(f"| [{name}](https://pypi.org/project/{name}/) | `{ver}` | {lic[(name, ver)]} | "
                   f"{', '.join(sorted(set(used[(name, ver)])))} |")
    with open(os.path.join(ROOT, "docs", "licenses-python.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"✓ docs/licenses-python.md: {len(rows)} packages")


if __name__ == "__main__":
    main()
